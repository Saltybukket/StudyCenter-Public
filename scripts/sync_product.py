"""Track and safely refresh the explicitly scoped shared product source.

The source argument is the application package directory, never a data directory.
Hashes attest bytes, not functional parity. See --help for operations.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import sys
import tempfile

from check_public import check

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / "src/studycenter_public/core"
MANIFEST = ROOT / "packaging/product-source.json"
HASH = re.compile(r"[0-9a-f]{64}\Z")
FORBIDDEN = {".local", ".env", ".venv", "browser-profiles", "profiles", "data", "logs"}
TEXT = {".py", ".html", ".css", ".js", ".txt", ".json"}
ASSETS = {"static/quest-journey.webp", "static/studycenter.ico"}


def valid_name(name: str) -> bool:
    if not isinstance(name, str) or "\\" in name or ":" in name:
        return False
    p = PurePosixPath(name)
    if not name or str(p) != name or p.is_absolute() or any(x in {"", ".", ".."} or x.startswith(".") or x.lower() in FORBIDDEN for x in p.parts):
        return False
    return ((len(p.parts) == 1 and p.suffix == ".py") or
            (len(p.parts) == 2 and p.parts[0] == "templates" and p.suffix == ".html") or
            (p.parts[0] == "static" and len(p.parts) in (2, 3) and
             (len(p.parts) == 2 or p.parts[1] == "vendor") and
             (p.suffix in TEXT or name in ASSETS)))


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def inventory(directory: Path, *, source: bool = False) -> dict[str, bytes]:
    """Only enter application source directories; never inspect user data."""
    if directory.is_symlink() or not directory.is_dir():
        raise ValueError("source/product directory missing or linked")
    result = {}
    def walk(folder: Path):
        for item in sorted(folder.iterdir()):
            name = item.relative_to(directory).as_posix()
            if item.is_symlink() or getattr(item.lstat(), "st_file_attributes", 0) & 0x400:
                raise ValueError(f"linked path: {name}")
            if item.is_dir():
                if item.name == "__pycache__":
                    if not source:
                        # Generated bytecode is never shipped; reject everything else.
                        for cached in item.iterdir():
                            if cached.is_symlink() or not cached.is_file() or cached.suffix != ".pyc":
                                raise ValueError(f"unexpected cache content: {cached.relative_to(directory).as_posix()}")
                    continue
                if name in ("static", "static/vendor", "templates"):
                    walk(item)
                elif not source:
                    raise ValueError(f"unexpected product directory: {name}")
                # Unknown source directories may contain private data: do not enter.
            elif valid_name(name):
                result[name] = item.read_bytes()
            elif not source:
                raise ValueError(f"unexpected product file: {name}")
    walk(directory)
    return result


def gate(name: str, data: bytes) -> None:
    failures = check(name, data)
    if failures:
        raise ValueError(f"content gate failed: {name}: " + ", ".join(rule for _, rule in failures))


def load_manifest(path: Path) -> dict:
    doc = json.loads(path.read_text(encoding="utf-8"))
    if set(doc) != {"format", "files", "additions"} or doc["format"] != 1:
        raise ValueError("invalid manifest format")
    if not isinstance(doc["files"], dict) or not isinstance(doc["additions"], dict):
        raise ValueError("invalid manifest records")
    if set(doc["files"]) & set(doc["additions"]):
        raise ValueError("overlapping manifest paths")
    for name, record in doc["files"].items():
        if not valid_name(name) or not isinstance(record, dict) or set(record) != {"upstream_sha256", "shipped_sha256", "adaptation"}:
            raise ValueError(f"invalid manifest entry: {name}")
        if not all(isinstance(record[x], str) and HASH.fullmatch(record[x]) for x in ("upstream_sha256", "shipped_sha256")):
            raise ValueError(f"invalid hashes: {name}")
        reason = record["adaptation"]
        if not isinstance(reason, str) or ((record["upstream_sha256"] != record["shipped_sha256"]) != bool(reason.strip())):
            raise ValueError(f"adaptation reason mismatch: {name}")
    for name, record in doc["additions"].items():
        if not valid_name(name) or not isinstance(record, dict) or set(record) != {"shipped_sha256", "reason"} or not isinstance(record["shipped_sha256"], str) or not HASH.fullmatch(record["shipped_sha256"]) or not isinstance(record["reason"], str) or not record["reason"].strip():
            raise ValueError(f"invalid addition: {name}")
    # Metadata itself must satisfy the same public content policy.
    gate("product-source.json", path.read_bytes())
    return doc


def verify(doc: dict, public: Path, source: Path | None = None) -> None:
    shipped = inventory(public)
    expected = set(doc["files"]) | set(doc["additions"])
    if set(shipped) != expected:
        raise ValueError(f"product file set differs; missing={sorted(expected-set(shipped))}; extra={sorted(set(shipped)-expected)}")
    for name, data in shipped.items():
        record = doc["files"].get(name) or doc["additions"][name]
        if digest(data) != record["shipped_sha256"]:
            raise ValueError(f"shipped content drift: {name}")
        gate(name, data)
    if source is not None:
        upstream = inventory(source, source=True)
        if set(upstream) != set(doc["files"]):
            raise ValueError(f"upstream file set differs; missing={sorted(set(doc['files'])-set(upstream))}; extra={sorted(set(upstream)-set(doc['files']))}")
        for name, data in upstream.items():
            if digest(data) != doc["files"][name]["upstream_sha256"]:
                raise ValueError(f"upstream content drift: {name}")


def capture(baseline: Path, reasons: Path, public: Path, output: Path, source: Path | None = None) -> None:
    original = json.loads(baseline.read_text(encoding="utf-8"))
    why = json.loads(reasons.read_text(encoding="utf-8"))
    if original.get("format") != 1 or not isinstance(original.get("files"), dict) or set(why) != {"adaptations", "additions"}:
        raise ValueError("invalid baseline or reasons")
    upstream = original["files"]
    if any(not valid_name(n) or not isinstance(h, str) or not HASH.fullmatch(h) for n, h in upstream.items()):
        raise ValueError("invalid baseline paths or hashes")
    shipped = inventory(public)
    if not set(upstream) <= set(shipped):
        raise ValueError("baseline file missing from product")
    adapted = {n for n in upstream if digest(shipped[n]) != upstream[n]}
    added = set(shipped) - set(upstream)
    if set(why["adaptations"]) != adapted or set(why["additions"]) != added:
        raise ValueError(f"reasons must exactly cover adaptations={sorted(adapted)} and additions={sorted(added)}")
    doc = {"format": 1, "files": {n: {"upstream_sha256": h, "shipped_sha256": digest(shipped[n]), "adaptation": why["adaptations"].get(n, "")} for n, h in sorted(upstream.items())}, "additions": {n: {"shipped_sha256": digest(shipped[n]), "reason": why["additions"][n]} for n in sorted(added)}}
    # Validate before touching the manifest; use a temporary sibling and retain no partial record.
    encoded = (json.dumps(doc, indent=2, ensure_ascii=False) + "\n").encode()
    gate("product-source.json", encoded)
    for name, data in shipped.items(): gate(name, data)
    if source is not None:
        actual = inventory(source, source=True)
        if set(actual) != set(upstream) or any(digest(actual[n]) != upstream[n] for n in actual):
            raise ValueError("baseline does not match current source snapshot")
    with tempfile.NamedTemporaryFile(dir=output.parent, prefix=output.name + ".", suffix=".tmp", delete=False) as stream:
        temp = Path(stream.name)
        stream.write(encoded)
    try:
        candidate = load_manifest(temp)
        verify(candidate, public, source)
        os.replace(temp, output)
    finally:
        temp.unlink(missing_ok=True)


def update(doc: dict, public: Path, source: Path, manifest: Path) -> None:
    verify(doc, public)
    upstream = inventory(source, source=True)
    if set(upstream) != set(doc["files"]):
        raise ValueError("upstream file set changed; review additions or removals manually")
    changes = {}
    for name, data in upstream.items():
        record = doc["files"][name]
        if digest(data) != record["upstream_sha256"]:
            if record["adaptation"]:
                raise ValueError(f"upstream changed adapted file; merge manually: {name}")
            gate(name, data)
            changes[name] = data
    # Preflight everything before any writes. No automatic overwrite of adaptations.
    for name, data in changes.items():
        (public / name).write_bytes(data)
        record = doc["files"][name]
        record["upstream_sha256"] = record["shipped_sha256"] = digest(data)
    manifest.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("action", choices=("verify", "capture", "update"))
    p.add_argument("--source", type=Path, help="application package directory, optionally verify current dirty source")
    p.add_argument("--baseline", type=Path, help="initial upstream hash map for capture")
    p.add_argument("--reasons", type=Path, help="JSON object with adaptations and additions maps")
    a = p.parse_args()
    try:
        if a.action == "capture":
            if not a.baseline or not a.reasons: p.error("capture requires --baseline and --reasons")
            capture(a.baseline, a.reasons, PUBLIC, MANIFEST, a.source)
        elif a.action == "update":
            if not a.source: p.error("update requires --source")
            update(load_manifest(MANIFEST), PUBLIC, a.source, MANIFEST)
        else:
            verify(load_manifest(MANIFEST), PUBLIC, a.source)
        print(f"product source {a.action}: OK (hashes do not establish behavioral parity)")
        return 0
    except (ValueError, OSError, KeyError, TypeError, json.JSONDecodeError) as exc:
        print(f"product source {a.action} failed: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
